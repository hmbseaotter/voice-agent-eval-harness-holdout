#!/usr/bin/env python3
"""Write the agent personas this set uses into `PERSONAS`, or check the file is current.

    python tools/declare_personas.py            # write PERSONAS
    python tools/declare_personas.py --check    # fail if it is out of date

WHY THIS EXISTS
---------------
The harness's entity register declares thirteen agent personas and says they are
used in every call -- the *design* set's. This set uses others, declared in
neither repository, so `test_every_agent_persona_is_declared` could not be
ported here: porting a check whose declaration does not exist commits a
knowingly red build.

A persona is Class 1 vocabulary rather than a label. The register's own argument
is that a name used and not declared "means the corpus invented vocabulary its
own canonical list does not know about, and every check keyed to the list
silently stops covering it".

WHY IT IS A GENERATOR AND NOT A LIST SOMEBODY TYPES
---------------------------------------------------
Extracting a persona is deterministic -- a pattern over the agent's
self-introduction -- so the names can be produced by a program. **Nobody has to
read a transcript to declare them, and no session has to be cleared to do it.**
That matters more than the convenience: every other route to this file involved
a reader, and a rule enforced by a reader's restraint is the shape this project
replaces wherever it can.

The pattern is a copy of `_agent_personas` in the harness's
`tests/test_corpus_hygiene.py`, for the same reason `_sourced_by` is a copy: it
is a private helper in a test tree, and a test module is not an importable
interface. `test_the_persona_pattern_still_matches_the_harness_one` holds the
two together.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TRANSCRIPTS = REPO_ROOT / "transcripts"
DECLARATION = REPO_ROOT / "PERSONAS"

#: The agent's self-introduction. Copied from the harness's `_agent_personas`.
PERSONA_PATTERN = re.compile(r"\bthis is ([A-Z][a-z]+)\b")

HEADER = """# The agent personas used in this set, one per line.
#
# Generated by `tools/declare_personas.py`, not written by hand. Regenerate with
# that tool and commit the result; CI re-runs it with --check, so this file
# cannot go stale the next time a transcript lands.
#
# It exists because a persona is Class 1 vocabulary and the harness's register
# declares the design set's, not these. Declaring them here rather than there
# keeps held-out-derived names on the held-out side, which is the conservative
# choice while nobody has ruled on whether they may cross.
"""


def _harness_root() -> Path | None:
    for candidate in (
        Path(value) if (value := os.environ.get("HARNESS_ROOT")) else None,
        REPO_ROOT / ".harness",
        REPO_ROOT.parent / "voice-agent-eval-harness",
    ):
        if candidate is not None and (candidate / "corpus" / "policies").is_dir():
            return candidate
    return None


def personas() -> dict[str, str]:
    """`{call id: persona}` for every transcript that introduces the agent."""
    harness = _harness_root()
    if harness is not None and str(harness / "src") not in sys.path:
        sys.path.insert(0, str(harness / "src"))
    from harness.core.events import EventKind
    from harness.corpus.text_adapter import parse_call

    found: dict[str, str] = {}
    for path in sorted(TRANSCRIPTS.glob("CALL-*.txt")):
        call = parse_call(path)
        for event in call.events:
            if event.kind is not EventKind.AGENT:
                continue
            match = PERSONA_PATTERN.search(event.body)
            if match:
                found[call.record.call_id] = match.group(1)
                break
    return found


def render(found: dict[str, str]) -> str:
    return HEADER + "\n" + "\n".join(sorted(set(found.values()))) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if PERSONAS is missing or out of date",
    )
    args = parser.parse_args(argv)

    if _harness_root() is None:
        print(
            "error: the harness was not found, and its parser is what reads a transcript.\n"
            "Set HARNESS_ROOT, check it out to .harness, or clone it alongside this one.",
            file=sys.stderr,
        )
        return 1

    found = personas()
    if not found:
        print("error: no agent persona was read from any transcript.", file=sys.stderr)
        print(
            "Either the agent stopped introducing itself or the phrasing changed",
            file=sys.stderr,
        )
        print(
            "and this pattern has gone blind. Do not commit an empty declaration.",
            file=sys.stderr,
        )
        return 1

    missing = sorted({path.stem for path in TRANSCRIPTS.glob("CALL-*.txt")} - set(found))
    if missing:
        # The same two-sided assertion the harness's check makes: every call must
        # yield a persona, so a rewording that stops the pattern matching fails
        # loudly rather than quietly shrinking the set.
        print(f"error: no persona could be read from {missing}.", file=sys.stderr)
        return 1

    rendered = render(found)
    if args.check:
        if not DECLARATION.is_file():
            print("error: PERSONAS does not exist. Run this tool without --check.", file=sys.stderr)
            return 1
        if DECLARATION.read_text(encoding="utf-8") != rendered:
            print("error: PERSONAS is out of date. Re-run this tool and commit.", file=sys.stderr)
            return 1
        print(f"PERSONAS is current: {len(set(found.values()))} personas across {len(found)} calls")
        return 0

    DECLARATION.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote PERSONAS: {len(set(found.values()))} personas across {len(found)} calls")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
