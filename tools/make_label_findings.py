#!/usr/bin/env python3
"""Generate the held-out findings from the drafts and the owner's ledger.

    python tools/make_label_findings.py
    python tools/make_label_findings.py --check

WHY THIS IS GENERATED RATHER THAN WRITTEN
-----------------------------------------
`PHASE-5-LABELS.md` §5 step 7, which is the design set's route (D36). The owner
rules on every draft in `private/labels/ledger.yaml`, and this projects the
drafts and the rulings into `private/labels/findings.yaml`, the way the harness's
`tools/make_gold_set.py` projects its own. A correction to a ruling then cannot
drift from the file built out of it, and `--check` says whether it has.

WHAT WINS WHERE
---------------
`owner`, `detectable_by` and `tier` come from the ledger and from nowhere else:
`validate_labels.parse_drafts` refuses a draft that carries them. That is the
one departure from the design set, whose drafts proposed classifications the
ledger then overrode. Here the proposals are the two reviewers' notes, and a
draft restating them as values would put a default in front of the owner (D38).

`observation`, `evidence` and `consequence` come from the ledger where it
carries them, under `accept-with-edits`, and from the drafts otherwise.

`verdict`, `origin` and `note` belong to the ledger and are projected out, since
the harness's loader tolerates no key beyond its eight. `origin` stays in the
ledger so that phase 5 can report agreement with and without reviewer-only
findings (§5 step 5).

THE LEDGER
----------
    adjudications:
      - id: HF-NN
        verdict: accept | accept-with-edits | reject
        origin: owner | reviewer | both
        note: the reasoning, on every ruling
        owner: agent | platform | data            not on a reject
        detectable_by: assert | judge | human     not on a reject
        tier: defect | question                   not on a reject
        observation, evidence, consequence        replacement text, accept-with-edits only

Every draft needs exactly one ruling, and every ruling a draft. A plain accept
needs a note too, because a ruling with no reasoning cannot be told apart from a
default.

WHAT IT PRINTS
--------------
Counts, and for a refusal the draft or ruling and the rule it breaks. Never the
text, and never a ruled value.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

sys.path.insert(0, str(Path(__file__).resolve().parent))

from make_label_worksheet import FREEZE_TAG, PRIVATE, REPO_ROOT, freeze_commit, harness_root
from validate_labels import HELDOUT_ID, LABELS, RULED, id_order, parse_drafts, yaml_problem

if TYPE_CHECKING:  # pragma: no cover - types only, and the harness may be absent
    from harness.core.findings import Finding

VERDICTS: Final[frozenset[str]] = frozenset({"accept", "accept-with-edits", "reject"})
ORIGINS: Final[frozenset[str]] = frozenset({"owner", "reviewer", "both"})
TEXT: Final[tuple[str, ...]] = ("observation", "evidence", "consequence")
LEDGER_KEYS: Final[frozenset[str]] = frozenset({"id", "verdict", "origin", "note", *RULED, *TEXT})


@dataclass(frozen=True, slots=True)
class Generated:
    """A findings document, and the counts reported about it."""

    text: str
    findings: int
    drafts: int
    rejected: int


def _header(freeze_sha: str) -> str:
    return (
        "# The held-out findings. Generated by `tools/make_label_findings.py` from the\n"
        "# drafts and the owner's adjudication ledger, which stay private.\n"
        "#\n"
        f"# {FREEZE_TAG}: {freeze_sha}\n"
        "#\n"
        "# Do not edit this file: edit the ledger and regenerate. Once it is sealed, the\n"
        "# manifest is what shows it unchanged, because its inputs are never published.\n"
        "#\n"
        "# The rows, and each row's owner, detectable_by and tier, are a human's\n"
        "# judgment (D10).\n"
    )


# The renderer is `tools/make_gold_set.py`'s, copied so the two gold sets read alike:
# folded scalars where line breaks are only wrapping, literal ones where they are
# content (D22). It is not compared with the original, because a difference in layout
# changes no rule. What would matter is a row that does not load back as it was meant,
# and `render` refuses that by reading its own output with the harness's loader.


def _block(text: str, indent: str) -> str:
    """A YAML literal scalar, for text whose line breaks are part of the content."""
    return "\n".join(indent + line if line.strip() else "" for line in str(text).split("\n"))


def _fold(text: str, indent: str) -> str:
    """A YAML folded scalar, wrapped the way the harness's candidates file wraps."""
    lines: list[str] = []
    cur = ""
    for word in str(text).split():
        if cur and len(indent) + len(cur) + 1 + len(word) > 78:
            lines.append(indent + cur)
            cur = word
        else:
            cur = f"{cur} {word}" if cur else word
    if cur:
        lines.append(indent + cur)
    return "\n".join(lines)


def _marker(text: object) -> str:
    """`|-` where line breaks are content, `>-` where they are only wrapping."""
    return "|-" if "\n" in str(text) else ">-"


def _scalar(text: object, indent: str) -> str:
    return _block(str(text), indent) if "\n" in str(text) else _fold(str(text), indent)


def _render(entry: dict[str, Any]) -> str:
    out = [
        f"  - id: {entry['id']}",
        f"    call_ref: {entry['call_ref']}",
        f"    owner: {entry['owner']}",
    ]
    out.append("    observation: " + _marker(entry["observation"]))
    out.append(_scalar(entry["observation"], "      "))
    out.append("    evidence:")
    for fragment in entry["evidence"]:
        out.append("      - " + _marker(fragment))
        out.append(_scalar(fragment, "        "))
    out.append("    consequence: " + _marker(entry["consequence"]))
    out.append(_scalar(entry["consequence"], "      "))
    out.append(f"    detectable_by: {entry['detectable_by']}")
    out.append(f"    tier: {entry['tier']}")
    return "\n".join(out)


def _tidy(value: Any) -> Any:
    """Text without surrounding whitespace, such as the newline YAML's `>` and `|` leave behind.

    An encoding artifact of how the ledger was written, not part of what it says, and
    left in place it would render a one-line observation as a literal block.
    """
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, list):
        return [item.strip() if isinstance(item, str) else item for item in value]
    return value


def _shape(text: str) -> tuple[str, ...]:
    """Text as the renderer promises to keep it: its lines, each with its spacing normalized."""
    return tuple(" ".join(line.split()) for line in text.split("\n"))


def _as_written(row: dict[str, Any]) -> tuple[object, ...]:
    return (
        row["id"],
        row["call_ref"],
        row["owner"],
        row["detectable_by"],
        row["tier"],
        _shape(row["observation"]),
        tuple(_shape(fragment) for fragment in row["evidence"]),
        _shape(row["consequence"]),
    )


def _as_read(finding: Finding) -> tuple[object, ...]:
    return (
        finding.id,
        finding.call_ref,
        finding.owner.value,
        finding.detectable_by.value,
        finding.tier.value,
        _shape(finding.observation),
        tuple(_shape(fragment) for fragment in finding.evidence),
        _shape(finding.consequence),
    )


def _parse_ledger(text: str) -> tuple[dict[str, dict[str, Any]], list[str]]:
    """The rulings by draft id, and every way the ledger departs from its schema."""
    import yaml
    from harness.core.findings import DetectableBy, Owner, Tier

    enums: dict[str, type[StrEnum]] = {"owner": Owner, "detectable_by": DetectableBy, "tier": Tier}
    allowed = {key: [str(member.value) for member in enum] for key, enum in enums.items()}

    try:
        document = yaml.safe_load(text)
    except yaml.YAMLError as error:
        return {}, [yaml_problem("ledger.yaml", error)]
    entries = document.get("adjudications") if isinstance(document, dict) else None
    if not isinstance(entries, list) or not entries:
        return {}, ["ledger.yaml: expected a mapping whose `adjudications` is a non-empty list"]

    rulings: dict[str, dict[str, Any]] = {}
    problems: list[str] = []
    for position, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            problems.append(f"ruling {position}: expected a mapping")
            continue
        raw_id = entry.get("id")
        shaped = isinstance(raw_id, str) and HELDOUT_ID.match(raw_id) is not None
        where = f"the ruling on {raw_id}" if shaped else f"ruling {position}"
        before = len(problems)

        if not shaped:
            problems.append(f"{where}: its id is not shaped HF-NN")
        unknown = sorted(str(key) for key in entry if key not in LEDGER_KEYS)
        if unknown:
            problems.append(f"{where}: unknown key(s) {', '.join(unknown)}")
        verdict = entry.get("verdict")
        if not isinstance(verdict, str) or verdict not in VERDICTS:
            # Without this, `rejcet` is not a rejection: every string but `reject` reads as assent.
            problems.append(f"{where}: verdict must be one of {', '.join(sorted(VERDICTS))}")
        origin = entry.get("origin")
        if not isinstance(origin, str) or origin not in ORIGINS:
            problems.append(f"{where}: origin must be one of {', '.join(sorted(ORIGINS))}")
        note = entry.get("note")
        if not isinstance(note, str) or not note.strip():
            problems.append(f"{where}: note is required, on a plain accept too")

        ruled = [key for key in RULED if key in entry]
        replaced = [key for key in TEXT if key in entry]
        if verdict == "reject" and (ruled or replaced):
            problems.append(
                f"{where}: a reject carries {', '.join(ruled + replaced)}; a rejected draft "
                "publishes nothing, so rule nothing on it"
            )
        if verdict in {"accept", "accept-with-edits"}:
            absent = [key for key in RULED if key not in entry]
            if absent:
                problems.append(f"{where}: missing {', '.join(absent)}")
        if verdict == "accept" and replaced:
            problems.append(
                f"{where}: verdict is accept yet it carries {', '.join(replaced)}; use "
                "accept-with-edits, or drop the text"
            )
        for key in ruled:
            if entry[key] not in allowed[key]:
                problems.append(f"{where}: {key} must be one of {', '.join(allowed[key])}")
        for key in ("observation", "consequence"):
            value = entry.get(key)
            if key in entry and (not isinstance(value, str) or not value.strip()):
                problems.append(f"{where}: replacement {key} must be a non-empty string")
        evidence = entry.get("evidence")
        if "evidence" in entry and (
            not isinstance(evidence, list)
            or not evidence
            or not all(isinstance(fragment, str) and fragment.strip() for fragment in evidence)
        ):
            problems.append(
                f"{where}: replacement evidence must be a non-empty list of non-empty strings"
            )

        if len(problems) > before or not isinstance(raw_id, str):
            continue
        if raw_id in rulings:
            problems.append(f"{where}: a second ruling on the same draft")
            continue
        rulings[raw_id] = entry
    return rulings, problems


def render(
    drafts_text: str, ledger_text: str, *, freeze_sha: str
) -> tuple[Generated | None, list[str]]:
    """The findings document, or every reason it cannot be generated."""
    import yaml
    from harness.core.findings import REQUIRED_KEYS, FindingsError, parse_findings

    drafts, problems = parse_drafts(drafts_text)
    if not problems:
        problems = [
            f"draft {position}: its id is not shaped HF-NN"
            for position, row in enumerate(drafts, start=1)
            if HELDOUT_ID.match(row.id) is None
        ]
    rulings, ledger_problems = _parse_ledger(ledger_text)
    problems += ledger_problems
    if problems:
        return None, problems

    by_id = {row.id: row for row in drafts}
    unruled = sorted(set(by_id) - set(rulings), key=id_order)
    if unruled:
        problems.append(
            f"no ruling on {', '.join(unruled)}; every draft is adjudicated before any finding "
            "exists (D36)"
        )
    orphaned = sorted(set(rulings) - set(by_id), key=id_order)
    if orphaned:
        problems.append(f"the ledger rules on ids no draft carries: {', '.join(orphaned)}")
    if problems:
        return None, problems

    rows: list[dict[str, Any]] = []
    for finding_id in sorted(by_id, key=id_order):
        ruling, draft = rulings[finding_id], by_id[finding_id]
        if ruling["verdict"] == "reject":
            continue
        row: dict[str, Any] = {"id": finding_id, "call_ref": draft.call_ref}
        row |= {key: ruling[key] for key in RULED}
        row |= {
            "observation": _tidy(ruling.get("observation", draft.observation)),
            "evidence": _tidy(ruling.get("evidence", list(draft.evidence))),
            "consequence": _tidy(ruling.get("consequence", draft.consequence)),
        }
        missing = [key for key in REQUIRED_KEYS if key not in row]
        if missing:
            return None, [
                f"the harness's loader now requires {', '.join(missing)}, which this tool does "
                "not write"
            ]
        rows.append(row)
    if not rows:
        return None, ["every draft was rejected, and a findings document holds at least one"]

    text = f"{_header(freeze_sha)}\nfindings:\n" + "\n\n".join(_render(row) for row in rows) + "\n"
    try:
        loaded = parse_findings(text)
    except yaml.YAMLError as error:
        return None, [yaml_problem("the generated findings.yaml", error)]
    except FindingsError as error:
        return None, [f"the generated findings.yaml does not load: {error}"]
    unfaithful = [
        row["id"]
        for row, finding in zip(rows, loaded, strict=True)
        if _as_written(row) != _as_read(finding)
    ]
    if unfaithful:
        return None, [
            f"{', '.join(unfaithful)}: would not read back as written, which is a fault in the "
            "renderer rather than in the ledger"
        ]
    return Generated(text, len(rows), len(drafts), len(drafts) - len(rows)), []


def _inside(path: Path, root: Path) -> bool:
    return path == root or root in path.parents


def build(*, harness: Path, labels: Path = LABELS, check: bool = False) -> int:
    """Write `findings.yaml` under `labels`, or with `check` compare it; refuse and say why."""
    sha = freeze_commit(harness)
    if sha is None:
        print(
            f"error: {FREEZE_TAG} does not resolve in {harness}. Held-out findings exist only "
            "after the freeze (D21), so this refuses. If the tag exists on GitHub, fetch tags "
            "into that checkout and run this again.",
            file=sys.stderr,
        )
        return 1
    target = labels.resolve()
    if _inside(target, REPO_ROOT.resolve()) and not _inside(target, PRIVATE.resolve()):
        print(
            f"error: {labels} is inside this repository but outside private/, where labels could "
            "be committed before the reveal (D21). Keep them under private/.",
            file=sys.stderr,
        )
        return 2
    drafts, ledger, out = labels / "drafts.yaml", labels / "ledger.yaml", labels / "findings.yaml"
    for required in (drafts, ledger):
        if not required.is_file():
            print(f"error: {required} does not exist", file=sys.stderr)
            return 1

    if str(harness / "src") not in sys.path:
        sys.path.insert(0, str(harness / "src"))
    generated, problems = render(
        drafts.read_text(encoding="utf-8"), ledger.read_text(encoding="utf-8"), freeze_sha=sha
    )
    if generated is None:
        outcome = "not checked" if check else "not written"
        print(f"refused: {len(problems)} problem(s), so {out.name} was {outcome}", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1

    if check:
        if not out.is_file():
            print(f"{out} has not been generated", file=sys.stderr)
            return 1
        # Bytes, not text: the manifest seals bytes, and a line-ending change is a change.
        if out.read_bytes() != generated.text.encode("utf-8"):
            print(f"{out} disagrees with the drafts and the ledger; regenerate it", file=sys.stderr)
            return 1
        print(f"{out} agrees with the drafts and the ledger: {generated.findings} findings")
        return 0

    with out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated.text)
    print(
        f"wrote {out}: {generated.findings} findings from {generated.drafts} drafts, "
        f"{generated.rejected} rejected, under {FREEZE_TAG} {sha[:12]}"
    )
    print("next: python tools/validate_labels.py findings")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the held-out findings from the drafts and the owner's ledger."
    )
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if findings.yaml disagrees with its inputs"
    )
    args = parser.parse_args(argv)

    harness = harness_root()
    if harness is None:
        print(
            "error: the harness was not found, and it holds the loader and the freeze tag.\n"
            "Set HARNESS_ROOT, check it out to .harness, or clone it alongside this one.",
            file=sys.stderr,
        )
        return 1
    return build(harness=harness, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
